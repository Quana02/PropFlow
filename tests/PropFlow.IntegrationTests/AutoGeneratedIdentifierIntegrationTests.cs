    [Fact]
    public async Task Schedule_ConcurrentCreatesAllocateUniqueSuffixes()
    {
        await using var owner = await MaintenanceFixture.CreateAsync();
        var start = new DateTimeOffset(2031, 1, 2, 1, 0, 0, TimeSpan.Zero);
        var codes = await Task.WhenAll(Enumerable.Range(0, 4).Select(async index =>
        {
            await using var isolated = await MaintenanceFixture.CreateAsync();
            var schedule = await isolated.Service.CreateScheduleAsync(new("CLIENT", $"concurrent-{index}", start, FacilityId: isolated.FacilityId, Description: "fixture"), isolated.Actor, default);
            owner.ScheduleIds.Add(schedule.Id); isolated.SuppressCleanup = true; return schedule.ScheduleCode;
        }));
        Assert.Equal(4, codes.Distinct(StringComparer.Ordinal).Count());
        Assert.All(codes, code => Assert.Matches("^LBT-KHUTEST-020131(-00[2-4])?$", code));
    }

