    [Fact]
    public async Task Schedule_GeneratesAssetVariantsSuffixAndKeepsCodeOnUpdate()
    {
        await using var scope = await MaintenanceFixture.CreateAsync();
        var start = new DateTimeOffset(2026, 10, 12, 2, 0, 0, TimeSpan.Zero);
        var facility = await scope.Service.CreateScheduleAsync(new("CLIENT", "F", start, FacilityId: scope.FacilityId, Description: "fixture"), scope.Actor, default);
        var equipment = await scope.Service.CreateScheduleAsync(new("CLIENT", "E", start, EquipmentId: scope.EquipmentId, Description: "fixture"), scope.Actor, default);
        var both = await scope.Service.CreateScheduleAsync(new("CLIENT", "B", start, FacilityId: scope.FacilityId, EquipmentId: scope.EquipmentId, Description: "fixture"), scope.Actor, default);
        var duplicate = await scope.Service.CreateScheduleAsync(new("CLIENT", "F2", start, FacilityId: scope.FacilityId, Description: "fixture"), scope.Actor, default);
        foreach (var id in new[] { facility.Id, equipment.Id, both.Id, duplicate.Id }) scope.ScheduleIds.Add(id);
        Assert.Equal("LBT-KHUTEST-121026", facility.ScheduleCode);
        Assert.Equal("LBT-MAYTEST-121026", equipment.ScheduleCode);
        Assert.Equal("LBT-KHUTEST-MAYTEST-121026", both.ScheduleCode);
        Assert.Equal(facility.ScheduleCode + "-002", duplicate.ScheduleCode);
        var updated = await scope.Service.UpdateScheduleAsync(facility.Id, new("changed", start.AddDays(1), FacilityId: scope.FacilityId, Description: "fixture"), scope.Actor, default);
        Assert.Equal(facility.ScheduleCode, updated.ScheduleCode);
    }

    [Fact]
    public async Task Task_GeneratesEquipmentAndCommonCodes_AndScheduleTaskUsesScheduleAsset()
    {
        await using var scope = await MaintenanceFixture.CreateAsync();
        var start = new DateTimeOffset(2026, 10, 12, 2, 0, 0, TimeSpan.Zero);
        var equipmentTask = await scope.Service.CreateTaskAsync(new("CLIENT", "E", Description: "fixture", EquipmentId: scope.EquipmentId), scope.Actor, default);
        var commonTask = await scope.Service.CreateTaskAsync(new("CLIENT", "C", Description: "fixture"), scope.Actor, default);
        var schedule = await scope.Service.CreateScheduleAsync(new("CLIENT", "S", start, FacilityId: scope.FacilityId, Description: "fixture"), scope.Actor, default);
        var scheduledTask = await scope.Service.CreateTaskAsync(new("CLIENT", "ST", schedule.Id), scope.Actor, default);
        foreach (var id in new[] { equipmentTask.Id, commonTask.Id, scheduledTask.Id }) scope.TaskIds.Add(id);
        scope.ScheduleIds.Add(schedule.Id);
        Assert.StartsWith("CVBT-MAYTEST-", equipmentTask.TaskNumber);
