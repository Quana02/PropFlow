        public Task<MaintenanceStaffRecord?> GetActiveStaffAsync(Guid id, CancellationToken ct) => Task.FromResult<MaintenanceStaffRecord?>(null);
        public Task NotifyTaskUpdatedAsync(Guid id, IReadOnlyCollection<Guid> recipientStaffUserIds, CancellationToken ct = default) => Task.CompletedTask;
        public async ValueTask DisposeAsync() { if (!SuppressCleanup) { var tasks = await Db.MaintenanceTasks.Where(x => TaskIds.Contains(x.Id)).ToListAsync(); Db.RemoveRange(tasks); var schedules = await Db.MaintenanceSchedules.Where(x => ScheduleIds.Contains(x.Id)).ToListAsync(); Db.RemoveRange(schedules); await Db.SaveChangesAsync(); } await Db.DisposeAsync(); }
    }

    private sealed class FixedClock(DateTimeOffset instant) : TimeProvider
    {
        public override DateTimeOffset GetUtcNow() => instant;
    }

    private sealed class FixedBuildingTimeZone(string id) : ICurrentBuildingTimeZone
    {
        public Task<string> GetAsync(CancellationToken ct) => Task.FromResult(id);
    }
