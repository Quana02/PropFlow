        Assert.StartsWith("CVBT-KHUTEST-", scheduledTask.TaskNumber);
        Assert.All(await scope.Db.MaintenanceTasks.Where(x => scope.TaskIds.Contains(x.Id)).Select(x => x.TaskNumber).ToArrayAsync(), code => Assert.DoesNotContain("CLIENT", code));
    }

    [Fact]
    public async Task Task_GeneratesMonotonicSequenceForSameAssetPrefix()
    {
        await using var scope = await MaintenanceFixture.CreateAsync();
        var created = new List<MaintenanceTaskDto>();
        for (var index = 0; index < 3; index++)
        {
            var task = await scope.Service.CreateTaskAsync(new("CLIENT", $"T{index}", Description: "fixture", EquipmentId: scope.EquipmentId), scope.Actor, default);
            scope.TaskIds.Add(task.Id);
            created.Add(task);
        }
        Assert.Equal(["001", "002", "003"], created.Select(item => item.TaskNumber[^3..]).ToArray());
        var persisted = await scope.Db.MaintenanceTasks.Where(item => scope.TaskIds.Contains(item.Id)).Select(item => item.TaskNumber).ToArrayAsync();
        Assert.Equal(3, persisted.Distinct(StringComparer.Ordinal).Count());
    }

