    [Fact]
    public async Task Facility_GeneratesNormalizedCode_IgnoresClientCode_AndKeepsCodeOnUpdate()
    {
        await using var scope = await FixtureScope.CreateAsync();
        var facility = await scope.Facilities.CreateFacilityAsync(new CreateFacilityCommand(
            "CLIENT-MUST-BE-IGNORED", "Khu thử nghiệm", "Hồ bơi", "Tầng 9", CreatedBy: scope.Actor));
        scope.FacilityIds.Add(facility.Id);

        Assert.Equal("CSVC-HOBOI-TANG9", facility.Code);
        Assert.Equal(facility.Code, await scope.Db.Facilities.Where(x => x.Id == facility.Id).Select(x => x.Code).SingleAsync());

        var updated = await scope.Facilities.UpdateFacilityAsync(facility.Id,
            new UpdateFacilityCommand("Tên đã đổi", "Khác", "Tầng khác", UpdatedBy: scope.Actor));
        Assert.Equal("CSVC-HOBOI-TANG9", updated.Code);
        await Assert.ThrowsAsync<InvalidOperationException>(() => scope.Facilities.CreateFacilityAsync(
            new CreateFacilityCommand("OTHER", "Khác", "Hồ bơi", "Tầng 9", CreatedBy: scope.Actor)));
    }

    [Fact]
    public async Task Equipment_GeneratesSequence_IgnoresClientCode_AndConcurrentCreatesAreUnique()
    {
        await using var scope = await FixtureScope.CreateAsync();
        var name = "Máy bơm IT" + scope.Token;
        var first = await scope.Equipment.CreateEquipmentAsync(new CreateEquipmentCommand("CLIENT", name, EquipmentType: "TEST", CreatedBy: scope.Actor));
        scope.EquipmentIds.Add(first.Id);
        Assert.EndsWith("-001", first.Code);
        Assert.DoesNotContain("CLIENT", first.Code);

        var creates = Enumerable.Range(0, 3).Select(async _ =>
        {
            await using var isolated = await FixtureScope.CreateAsync(scope.Token);
            var created = await isolated.Equipment.CreateEquipmentAsync(new CreateEquipmentCommand("IGNORED", name, EquipmentType: "TEST", CreatedBy: isolated.Actor));
            // Preserve the row for the owning outer cleanup scope.
            scope.EquipmentIds.Add(created.Id);
            isolated.SuppressCleanup = true;
            return created.Code;
        });
        var codes = await Task.WhenAll(creates);
        Assert.Equal(codes.Length, codes.Distinct(StringComparer.Ordinal).Count());
        Assert.All(codes, code => Assert.StartsWith("TB-MAYBOMIT", code));

        var updated = await scope.Equipment.UpdateEquipmentAsync(first.Id,
            new UpdateEquipmentCommand("Tên thay đổi", EquipmentType: "TEST", UpdatedBy: scope.Actor));
        Assert.Equal(first.Code, updated.Code);
    }

    private sealed class FixtureScope : IAsyncDisposable
    {
        private FixtureScope(PropertyAssetsDbContext db, string token)
        {
            Db = db;
            Token = token;
            var store = new EfPropertyAssetsStore(db, new ManagerReadAccess());
            Facilities = new FacilityService(store);
            Equipment = new EquipmentService(store);
        }

        public PropertyAssetsDbContext Db { get; }
        public FacilityService Facilities { get; }
        public EquipmentService Equipment { get; }
        public Guid Actor { get; } = Guid.NewGuid();
        public string Token { get; }
        public ConcurrentBag<Guid> FacilityIds { get; } = [];
        public ConcurrentBag<Guid> EquipmentIds { get; } = [];
        public bool SuppressCleanup { get; set; }

        public static async Task<FixtureScope> CreateAsync(string? token = null)
        {
            var connection = TestDatabaseConfiguration.GetConnectionString();
            var builder = new NpgsqlConnectionStringBuilder(connection);
            if (!string.Equals(builder.Database, "propflow_test", StringComparison.Ordinal))
                throw new InvalidOperationException("Auto-code integration tests require propflow_test.");
            var db = new PropertyAssetsDbContext(new DbContextOptionsBuilder<PropertyAssetsDbContext>().UseNpgsql(connection).Options);
            // SqlQueryRaw<T> maps scalar values through the conventional Value column alias.
            if (!string.Equals(await db.Database.SqlQueryRaw<string>("SELECT current_database() AS \"Value\"").SingleAsync(), "propflow_test", StringComparison.Ordinal))
                throw new InvalidOperationException("Unexpected database target.");
            return new FixtureScope(db, token ?? Guid.NewGuid().ToString("N")[..8]);
        }

        public async ValueTask DisposeAsync()
        {
            if (!SuppressCleanup)
            {
                var equipment = await Db.Equipment.Where(x => EquipmentIds.Contains(x.Id)).ToListAsync();
                Db.Equipment.RemoveRange(equipment);
                await Db.SaveChangesAsync();
                var facilities = await Db.Facilities.Where(x => FacilityIds.Contains(x.Id)).ToListAsync();
                Db.Facilities.RemoveRange(facilities);
                await Db.SaveChangesAsync();
            }
            await Db.DisposeAsync();
        }
    }

    private sealed class ManagerReadAccess : IAssetReadAccess
    {
        public Task<AssetReadScope> GetScopeAsync(CancellationToken ct) => Task.FromResult(AssetReadScope.Manager);
    }

