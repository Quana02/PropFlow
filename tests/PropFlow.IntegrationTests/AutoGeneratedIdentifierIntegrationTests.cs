            return Task.FromResult(new MaintenanceFixture(new MaintenanceDbContext(new DbContextOptionsBuilder<MaintenanceDbContext>().UseNpgsql(connection).Options), clock, timeZone));
        }
        public Task<IReadOnlyList<MaintenanceAssetReference>> GetAvailableAsync(CancellationToken ct) => Task.FromResult<IReadOnlyList<MaintenanceAssetReference>>([]);
        public Task<MaintenanceAssetReference?> GetFacilityAsync(Guid id, CancellationToken ct) => Task.FromResult<MaintenanceAssetReference?>(id == FacilityId ? new(id, "CSVC-KHUTEST", "Khu test", "FACILITY", "UNDER_MAINTENANCE", "Tầng 9", null, "Khu test") : null);
